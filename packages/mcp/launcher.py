"""Launcher scripts for MCP servers.

Both CLIs can be told a server's environment directly — Claude in the JSON
config, Codex in `-c mcp_servers.<name>.env=...` — but the Codex form lands in
argv, where `ps` inside the workspace container shows it to the very agent the
secret is being kept from. So ANA spawns every server through a tiny script
instead: the script reads its environment from a sibling file, and the CLIs
only ever see a path.

The scripts live under the state directory, which is mounted into workspace
containers at the same path and is *outside* the session workspace — so an
agent reading them trips the gate's workspace-escape rule (see
packages/governance/workspace.py) instead of quietly collecting credentials.
"""
import os
import shlex
from pathlib import Path
from typing import Iterable

from packages.mcp.registry import ResolvedServer

LAUNCHER_DIRNAME = "mcp"


def launcher_dir(state_dir: os.PathLike | str) -> Path:
    path = Path(state_dir) / LAUNCHER_DIRNAME
    path.mkdir(parents=True, exist_ok=True)
    # The directory itself is owner-only: the env files inside carry secrets.
    os.chmod(path, 0o700)
    return path


def write_launcher(server: ResolvedServer, state_dir: os.PathLike | str) -> Path:
    """Writes (and overwrites) one server's launcher, returning its path."""
    directory = launcher_dir(state_dir)
    env_path = directory / f"{server.name}.env"
    script_path = directory / server.name

    # KEY='value' lines, single-quote escaped: the script sources this file, so
    # a value containing a quote or a newline must not become shell syntax.
    env_lines = "".join(
        f"export {key}={shlex.quote(value)}\n" for key, value in sorted(server.env.items())
    )
    env_path.write_text(env_lines, encoding="utf-8")
    os.chmod(env_path, 0o600)

    command = " ".join(shlex.quote(part) for part in (server.command, *server.args))
    script_path.write_text(
        "#!/bin/sh\n"
        "# Generated by ANA (packages/mcp/launcher.py). Edits are overwritten.\n"
        f'. "$(dirname "$0")/{server.name}.env"\n'
        f'exec {command} "$@"\n',
        encoding="utf-8",
    )
    os.chmod(script_path, 0o700)
    return script_path


def write_launchers(
    servers: Iterable[ResolvedServer], state_dir: os.PathLike | str
) -> dict[str, Path]:
    return {server.name: write_launcher(server, state_dir) for server in servers}
